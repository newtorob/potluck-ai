"""Download helper for inference benchmark models.

Usage:
    python bench/scripts/get_models.py [--model MODEL_ID] [--out bench/models/]

Downloads GGUF weights from HuggingFace, verifies SHA-256 against
bench/models/SHA256SUMS.txt, and refuses to use a mismatched file.

The catalog entry for 70B tracks known OOM state: if the model has never
been successfully tested (SHA256 unknown), the downloader marks it as
'hash_pending' and still downloads — you need the file to OOM cleanly.
"""

