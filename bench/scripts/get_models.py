_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
_DEFAULT_OUT = _REPO_ROOT / "bench" / "models"
_SHA256SUMS = _DEFAULT_OUT / "SHA256SUMS.txt"


def _load_known_hashes() -> dict[str, str]:
    """Read SHA256SUMS.txt -> {filename: sha256hex}."""
    if not _SHA256SUMS.exists():
        return {}
    known: dict[str, str] = {}
    for line in _SHA256SUMS.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) == 2:
            sha, fname = parts
            known[fname] = sha
    return known


def _save_known_hashes(known: dict[str, str]) -> None:
    _SHA256SUMS.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# SHA-256 checksums for Potluck inference benchmark models"]
    lines.append("# Format: <sha256hex>  <filename>")
    lines.append("# Generated by bench/scripts/get_models.py")
    lines.append("")
    for fname in sorted(known):
        lines.append(f"{known[fname]}  {fname}")
    _SHA256SUMS.write_text("\n".join(lines) + "\n")


def _sha256_file(path: Path, chunk_size: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(chunk_size), b""):
            h.update(chunk)
    return h.hexdigest()


def _download_with_progress(url: str, dest: Path) -> None:
    """Download url to dest with a simple progress printer."""
    import urllib.request

    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(".part")

    class _Reporter:
        def __init__(self) -> None:
            self._last_pct = -1

        def __call__(self, block_num: int, block_size: int, total_size: int) -> None:
            if total_size <= 0:
                return
            pct = min(100, int(block_num * block_size * 100 / total_size))
            if pct != self._last_pct and pct % 5 == 0:
                print(f"  {pct}%...", end="", flush=True)
                self._last_pct = pct

    print(f"  Downloading {url}")
    print(f"  -> {dest}")
    urllib.request.urlretrieve(url, tmp, reporthook=_Reporter())
    print()  # newline after progress dots
    tmp.rename(dest)


def download_model(
    model_id: str,
    out_dir: Path = _DEFAULT_OUT,
    *,
    skip_if_exists: bool = True,
    verify: bool = True,
) -> Path:
    """Download a model and verify its SHA-256.

    Returns the path to the downloaded file.
    Raises ValueError if the SHA-256 doesn't match a known-good hash.
    """
    if model_id not in MODELS:
        raise KeyError(
            f"Unknown model id {model_id!r}. "
            f"Valid ids: {list(MODELS.keys())}"
        )

    entry = MODELS[model_id]
    dest = out_dir / entry["filename"]

    if skip_if_exists and dest.exists():
        print(f"[{model_id}] Already exists: {dest}")
    else:
        _download_with_progress(entry["url"], dest)

    if not verify:
        return dest

    # --- SHA-256 verification ---
    known_hashes = _load_known_hashes()
    expected = known_hashes.get(entry["filename"]) or entry.get("sha256", "hash_pending")

    print(f"[{model_id}] Computing SHA-256...", end=" ", flush=True)
    actual = _sha256_file(dest)
    print(actual[:16] + "...")

    if expected == "hash_pending":
        # First time: record the hash as the canonical value
        print(f"[{model_id}] First download — pinning SHA-256 to {actual[:16]}...")
        known_hashes[entry["filename"]] = actual
        _save_known_hashes(known_hashes)
        print(f"[{model_id}] SHA256SUMS.txt updated.")
    elif actual != expected:
        raise ValueError(
            f"[{model_id}] SHA-256 MISMATCH for {dest}\n"
            f"  Expected: {expected}\n"
            f"  Actual:   {actual}\n"
            "File may be corrupted or the model was updated. "
            "Delete the file and re-download."
        )
    else:
        print(f"[{model_id}] SHA-256 OK.")

    return dest


def main() -> int:
    p = argparse.ArgumentParser(
        description="Download and verify GGUF models for the Potluck inference benchmark."
    )
    p.add_argument(
        "--model",
        choices=list(MODELS.keys()) + ["all", "all-small"],
        default="all-small",
        help=(
            "Model to download. 'all-small' downloads the three <=8B models "
            "(skip the 70B). 'all' downloads everything including the 70B OOM test."
        ),
    )
    p.add_argument(
        "--out",
        default=str(_DEFAULT_OUT),
        help=f"Output directory (default: {_DEFAULT_OUT})",
    )
    p.add_argument(
        "--no-verify",
        action="store_true",
        help="Skip SHA-256 verification (not recommended)",
    )
    p.add_argument(
        "--force",
        action="store_true",
        help="Re-download even if file already exists",
    )
    args = p.parse_args()

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.model == "all":
        targets = list(MODELS.keys())
    elif args.model == "all-small":
        targets = [k for k in MODELS if "70b" not in k]
    else:
        targets = [args.model]

    print(f"Downloading {len(targets)} model(s) to {out_dir}")
    print()

    for model_id in targets:
        entry = MODELS[model_id]
        print(f"==> {entry['display_name']} (~{entry['approx_size_gb']:.1f} GB)")
        if entry.get("oom_expected"):
            print(
                "    NOTE: This model is expected to OOM on 16GB unified memory. "
                "Downloading for OOM documentation."
            )
        try:
            path = download_model(
                model_id,
                out_dir=out_dir,
                skip_if_exists=not args.force,
                verify=not args.no_verify,
            )
            print(f"    Ready: {path}")
        except ValueError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
        print()

    print("Done. Run `make bench-inference` to execute the benchmark.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
