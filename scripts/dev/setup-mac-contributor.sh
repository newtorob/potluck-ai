# <plist version="1.0">
# <dict>
#   <key>Label</key>             <string>ai.potluck.contributor</string>
#   <key>ProgramArguments</key>
#   <array>
#     <string>VENV_PY_PATH_HERE</string>
#     <string>-m</string>
#     <string>potluck_local.contributor</string>
#   </array>
#   <key>WorkingDirectory</key>  <string>SIDECAR_DIR_PATH_HERE</string>
#   <key>RunAtLoad</key>         <true/>
#   <key>KeepAlive</key>         <true/>
#   <key>StandardOutPath</key>   <string>/tmp/potluck-contributor.log</string>
#   <key>StandardErrorPath</key> <string>/tmp/potluck-contributor.err</string>
# </dict>
