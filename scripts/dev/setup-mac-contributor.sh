#!/bin/bash
# One-shot macOS bootstrap for the Potluck contributor sidecar.
# Auto-detects whether to use the coordinator's LAN IP or its Tailscale IP
# based on what's reachable from this box.
#
# What it does:
#   1. Checks Python 3.11 + git + curl are present
#   2. Probes both the LAN IP and the Tailscale IP for the coordinator;
#      picks whichever responds and writes that into .env
#   3. Runs scripts/dev/install-contributor.py
#   4. Writes apps/desktop/python/.env with the dev smoke-test values
#   5. Smoke-launches the sidecar to confirm the handshake works
#   6. Drops a Start-PotluckContributor.command launcher on ~/Desktop
#      (double-click to start; close window or Ctrl-C to stop)
#
# This script does not install a launchd LaunchAgent - Macs are typically
# desktops, not always-on servers. If you want auto-start on login, see the
# launchd template at the bottom of this file (commented out).
#
# Idempotent - safe to re-run.

set -euo pipefail

# ---------- CONFIG ------------------------------------------------------------

# Coordinator hosts in probe order; the first to answer /transparency/fleet wins.
# Set POTLUCK_COORDINATOR_HOSTS to a space-separated list (LAN IP, then tailnet IP).
read -r -a CANDIDATE_HOSTS <<< "${POTLUCK_COORDINATOR_HOSTS:-127.0.0.1}"
COORDINATOR_PORT="8400"
BINARY_HASH="59b74f2ea0e8b6f23f3672336f90c97435b1dfa13ef7aabc1994b61c54c7d65a"
MEMBER_ID="00000000-0000-0000-0000-000000000001"

# ---------- helpers -----------------------------------------------------------

C_CYAN=$'\033[36m'; C_GREEN=$'\033[32m'; C_RED=$'\033[31m'; C_YELLOW=$'\033[33m'; C_OFF=$'\033[0m'
step() { printf "%s==> %s%s\n" "$C_CYAN" "$1" "$C_OFF"; }
pass() { printf "    %s[ok]   %s%s\n" "$C_GREEN" "$1" "$C_OFF"; }
warn() { printf "    %s[warn] %s%s\n" "$C_YELLOW" "$1" "$C_OFF"; }
fail() { printf "    %s[fail] %s%s\n" "$C_RED" "$1" "$C_OFF"; exit 1; }

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SIDECAR_DIR="$REPO_ROOT/apps/desktop/python"
VENV_PY="$SIDECAR_DIR/.venv/bin/python"
ENV_FILE="$SIDECAR_DIR/.env"

# ---------- 1. Prereqs --------------------------------------------------------

step "Checking prerequisites"
command -v git >/dev/null  || fail "git missing - 'xcode-select --install' or 'brew install git'"
command -v curl >/dev/null || fail "curl missing (should be built-in)"

PY=""
for c in python3.11 python3 python; do
    if command -v "$c" >/dev/null && "$c" -c 'import sys; sys.exit(0 if sys.version_info[:2]==(3,11) else 1)' 2>/dev/null; then
        PY="$c"; break
    fi
done
[ -n "$PY" ] || fail "Python 3.11 missing - 'brew install python@3.11' (then open a new shell so PATH refreshes)"
pass "found Python 3.11 ($PY)"

# ---------- 2. Coordinator probe ---------------------------------------------

step "Probing coordinator endpoints"
COORDINATOR_HOST=""
for host in "${CANDIDATE_HOSTS[@]}"; do
    if curl -fsS --max-time 3 "http://$host:$COORDINATOR_PORT/transparency/fleet" >/dev/null 2>&1; then
        COORDINATOR_HOST="$host"
        pass "reachable on $host"
        break
    else
        warn "no answer on $host"
    fi
done

if [ -z "$COORDINATOR_HOST" ]; then
    cat <<EOF
    ${C_RED}[fail]${C_OFF} Coordinator unreachable on any candidate host.

    Tried: ${CANDIDATE_HOSTS[*]}

    Common causes:
      1. Coordinator container stopped on the coordinator machine: check 'docker ps' there.
      2. The coordinator machine's IPs changed. On that machine:
           - LAN:       'ipconfig getifaddr en0'
           - Tailscale: 'tailscale ip -4'
         Set POTLUCK_COORDINATOR_HOSTS and re-run.
      3. This Mac isn't on the coordinator machine's LAN AND not on the same tailnet.
         Install Tailscale and sign in with the same account.

EOF
    exit 1
fi

COORDINATOR_URL="ws://$COORDINATOR_HOST:$COORDINATOR_PORT/peers/connect"

# ---------- 3. Install --------------------------------------------------------

step "Running scripts/dev/install-contributor.py"
"$PY" "$REPO_ROOT/scripts/dev/install-contributor.py"
[ -x "$VENV_PY" ] || fail "venv python missing at $VENV_PY after install"
pass "venv ready at $VENV_PY"

# ---------- 4. .env -----------------------------------------------------------

step "Writing $ENV_FILE"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-mac-contributor.sh - do not commit.
POTLUCK_COORDINATOR_URL=$COORDINATOR_URL
POTLUCK_BINARY_HASH=$BINARY_HASH
POTLUCK_MEMBER_ID=$MEMBER_ID
EOF
pass "wrote .env (host=$COORDINATOR_HOST)"

# ---------- 5. Smoke-launch ---------------------------------------------------

step "Smoke-launching sidecar (15s, then auto-kill)"
SMOKE_LOG="$(mktemp)"
( cd "$SIDECAR_DIR" && ( "$VENV_PY" -m potluck_local.contributor --verbose >"$SMOKE_LOG" 2>&1 & echo $! >"$SMOKE_LOG.pid" ) )
sleep 15
if [ -f "$SMOKE_LOG.pid" ]; then
    SMOKE_PID="$(cat "$SMOKE_LOG.pid")"
    kill "$SMOKE_PID" 2>/dev/null || true
    rm -f "$SMOKE_LOG.pid"
fi

if grep -q "session_opened" "$SMOKE_LOG"; then
    pass "session_opened observed - handshake worked"
elif grep -qE "binary_hash_mismatch|not in contributor_releases" "$SMOKE_LOG"; then
    fail "coordinator rejected binary_hash. Either .env didn't load or seed isn't in contributor_releases."
elif grep -q "missing POTLUCK_BINARY_HASH" "$SMOKE_LOG"; then
    fail ".env didn't load - check $ENV_FILE has the 3 vars."
else
    warn "didn't see session_opened in 15s. Last 10 lines:"
    tail -n 10 "$SMOKE_LOG" | sed 's/^/    /'
    warn "If those look healthy, try the launcher and watch live."
fi
rm -f "$SMOKE_LOG"

# ---------- 6. Desktop launcher ----------------------------------------------

step "Creating ~/Desktop/Start-PotluckContributor.command"
LAUNCHER="$HOME/Desktop/Start-PotluckContributor.command"
cat > "$LAUNCHER" <<EOF
#!/bin/bash
# Daily launcher for the Potluck contributor sidecar.
# Double-click to start; close the Terminal window (or Ctrl-C) to stop.
cd "$SIDECAR_DIR"
exec "$VENV_PY" -m potluck_local.contributor --verbose
EOF
chmod +x "$LAUNCHER"
pass "wrote $LAUNCHER (double-click to launch)"

# ---------- 7. Done -----------------------------------------------------------

cat <<EOF

${C_CYAN}==> Setup complete${C_OFF}

To start the sidecar:
    Double-click ~/Desktop/Start-PotluckContributor.command
  OR
    cd $SIDECAR_DIR && $VENV_PY -m potluck_local.contributor --verbose

To stop: close the Terminal window, or Ctrl-C.

Per-peer Ed25519 key: ~/Library/Application Support/Potluck/contributor/peer-key.pem

If you want auto-start at login, see the commented launchd plist at the
bottom of this script.

EOF

# ---------- Optional: launchd LaunchAgent for auto-start at login -------------
#
# Uncomment and adapt the block below if you want the sidecar to start
# automatically when you log in. Save the contents as
# ~/Library/LaunchAgents/ai.potluck.contributor.plist, then:
#
#   launchctl load ~/Library/LaunchAgents/ai.potluck.contributor.plist
#
# To stop:    launchctl unload ~/Library/LaunchAgents/ai.potluck.contributor.plist
# To remove:  rm ~/Library/LaunchAgents/ai.potluck.contributor.plist
#
# <?xml version="1.0" encoding="UTF-8"?>
